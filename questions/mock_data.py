ANSWERS_BY_QUESTION = {}
for offset, (question_id, title, text, tags) in enumerate(QUESTION_TOPICS):
    created_at = NEWEST_QUESTION_AT - timedelta(hours=offset * 2)
    texts = ANSWER_TEXTS.get(question_id, [])
    QUESTIONS.append({
        "id": question_id,
        "title": title,
        "text": text,
        "tags": tags,
        "code": HEADER_EXAMPLE if question_id == 35 else "",
        "author": AUTHORS[offset % len(AUTHORS)],
        "created_at": created_at,
        "score": 24 if offset == 0 else (question_id * 11) % 43,
        "vote": (0, 1, -1)[offset % 3],
        "answer_count": len(texts),
    })
    ANSWERS_BY_QUESTION[question_id] = [
        {
            "author": AUTHORS[(offset + number + 1) % len(AUTHORS)],
            "text": answer_text,
            "created_at": created_at + timedelta(minutes=20 * (number + 1)),
            "score": len(texts) - number,
            "vote": 1 if number == 0 else 0,
            "accepted": question_id == 35 and number == 0,
        }
        for number, answer_text in enumerate(texts)
    ]

POPULAR_QUESTIONS = sorted(
    QUESTIONS,
    key=lambda question: (question["score"], question["created_at"]),
    reverse=True,
)
